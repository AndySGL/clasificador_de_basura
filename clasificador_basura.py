etiquetas = ["Plastico", "Papel", "Metal"]

def analizar_residuo(ruta_imagen):
    # Abrimos la imagen
    imagen = Image.open(ruta_imagen).convert("RGB")

    # Adaptamos la imagen al tamaño que necesita el modelo
    imagen_procesada = ImageOps.fit(
        imagen,
        (224, 224),
        Image.Resampling.LANCZOS
    )

    # Convertimos los píxeles al formato esperado
    datos = np.asarray(imagen_procesada, dtype=np.float32)
    datos = (datos / 127.5) - 1.0
    datos = np.expand_dims(datos, axis=0)

    # Realizamos la inferencia
    predicciones = modelo.predict(datos, verbose=0)[0]

    # Comprobamos que las etiquetas coincidan con las salidas
    if len(etiquetas) != len(predicciones):
        raise ValueError(
            "La cantidad de etiquetas no coincide "
            "con las categorías del modelo."
        )

    # Buscamos la categoría con mayor predicción
    indice = int(np.argmax(predicciones))
    categoria = etiquetas[indice]
    confianza = float(predicciones[indice]) * 100

    # Mostramos la imagen analizada
    plt.figure(figsize=(5, 5))
    plt.imshow(imagen)
    plt.axis("off")
    plt.title("Residuo analizado")
    plt.show()

    # Mostramos los resultados
    print("Categoría detectada:", categoria)
    print(f"Confianza estimada: {confianza:.2f}%")

    # Ofrecemos una recomendación inicial
    if "plastico" in categoria.lower():
        print("Consejo: verifica si se acepta localmente.")
    elif "papel" in categoria.lower():
        print("Consejo: procura separarlo limpio y seco.")
    elif "metal" in categoria.lower():
        print("Consejo: revisa las normas locales de reciclaje.")

